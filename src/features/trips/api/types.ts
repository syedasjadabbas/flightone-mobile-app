/** Journey (My trips) types — same as the web's `client/lib/api/journey.api.ts`. */
export type JourneyFeedCapability = { provider: string; configured: boolean; canPollLive: boolean; reasons?: string[] };
export type JourneyPhase = "UPCOMING" | "IN_PROGRESS" | "COMPLETED" | "CANCELLED" | "PAUSED" | "UNKNOWN";
export type JourneyEvent = {
  id: string;
  watchId: string;
  type: string;
  severity: number;
  title: string;
  body?: string | null;
  fingerprint?: string | null;
  payload?: Record<string, unknown> | null;
  notifiedAt?: string | null;
  createdAt: string;
};
export type JourneySegment = {
  carrier: string | null;
  flightNumber: string | null;
  originCode: string;
  destinationCode: string;
  departDate: string | null;
  departTimeLocal: string | null;
  arriveDate: string | null;
  arriveTimeLocal: string | null;
  durationMinutes: number | null;
  layoverMinutesAfter: number | null;
  aircraft: string | null;
};
export type JourneyItineraryItem = {
  kind: "FLIGHT" | "HOTEL" | "TRANSFER" | string;
  flightNumber?: string | null;
  origin?: string | null;
  destination?: string | null;
  departAt?: string | null;
  arriveAt?: string | null;
  checkInDate?: string | null;
  checkOutDate?: string | null;
  confirmationRef?: string | null;
  transferRef?: string | null;
  pickupAt?: string | null;
  label?: string | null;
  carrier?: string | null;
  departDate?: string | null;
  departTimeLocal?: string | null;
  arriveDate?: string | null;
  arriveTimeLocal?: string | null;
  durationMinutes?: number | null;
  stops?: number | null;
  cabin?: string | null;
  segments?: JourneySegment[];
  hotelName?: string | null;
  city?: string | null;
  cityCode?: string | null;
  nights?: number | null;
  roomType?: string | null;
  boardType?: string | null;
};
export type JourneySummary = {
  product: string | null;
  tripType: "one_way" | "round_trip" | "multi_city" | "stay" | "unknown";
  stops: string[];
  flightCount: number;
  cabin: string | null;
  carrier: string | null;
  firstDepartDate: string | null;
  firstDepartTimeLocal: string | null;
  lastArriveDate: string | null;
  lastArriveTimeLocal: string | null;
  amountMinor: number | null;
  currency: string | null;
  supplierCode: string | null;
};
export type JourneyLiveFlight = {
  confirmed: boolean;
  dataStatus: string;
  snapshot: {
    status?: string | null;
    gate?: string | null;
    terminal?: string | null;
    minutesDelayed?: number | null;
    [key: string]: unknown;
  } | null;
  reason?: string | null;
};
export type JourneyWatch = {
  id: string;
  bookingId: string;
  userId: string;
  status: string;
  phase?: JourneyPhase;
  flightNumber: string | null;
  departAt: string | null;
  arriveAt: string | null;
  lastPolledAt: string | null;
  metadata: Record<string, unknown> | null;
  booking?: { id: string; status: string; product: string; ticketRef?: string | null } | null;
  itinerary?: JourneyItineraryItem[];
  summary?: JourneySummary;
  events?: JourneyEvent[];
  disruptions?: JourneyEvent[];
  liveFlight?: JourneyLiveFlight;
};
export type JourneyCapability = JourneyFeedCapability & { flightStatus?: JourneyFeedCapability };
export type JourneyPollResult = {
  dataStatus?: string;
  isFact?: boolean;
  reason?: string;
  events?: JourneyEvent[];
  watch?: JourneyWatch;
};
export type Paged<T> = { items: T[]; page?: number; pageSize?: number; total: number; totalPages?: number };
